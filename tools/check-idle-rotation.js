import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] })
try {
  const page = await browser.newPage({ viewport: { width: 900, height: 650 }, ignoreHTTPSErrors: true, reducedMotion: 'no-preference' })
  await page.route('**/src/main.js*', async (route) => {
    const response = await route.fetch()
    await route.fulfill({ response, body: `${await response.text()}\nglobalThis.inspectedView = { camera, controls };` })
  })
  const startTime = new Date()
  await page.clock.install({ time: startTime })
  await page.goto(process.argv[2] ?? 'http://127.0.0.1:3169')
  await page.waitForSelector('body.ready', { timeout: 60000 })
  await page.waitForFunction(() => globalThis.inspectedView)
  await page.clock.pauseAt(new Date())
  const view = () => page.evaluate(() => ({ rotating: inspectedView.controls.autoRotate, speed: inspectedView.controls.autoRotateSpeed, angle: inspectedView.controls.getAzimuthalAngle() }))
  await page.clock.runFor(100)
  assert.equal((await view()).rotating, true, 'ease-in must begin as soon as the scene is ready')
  await page.mouse.click(50, 50)
  await page.clock.runFor(100)
  await page.clock.fastForward(6800)
  assert.equal((await view()).rotating, false, 'the view must stay still during the first seven seconds')
  await page.mouse.move(60, 50)
  await page.clock.fastForward(200)
  const beginning = await view()
  assert.equal(beginning.rotating, true, 'rotation must start after seven seconds')
  await page.clock.fastForward(1900)
  const middle = await view()
  await page.clock.fastForward(2000)
  const cruising = await view()
  assert(beginning.speed < middle.speed && middle.speed < cruising.speed, 'rotation must ease in')
  assert(Math.abs(cruising.speed - 2 / 3) < 0.001, 'maximum speed must be one revolution per ninety seconds')
  assert.notEqual(cruising.angle, beginning.angle, 'the actual camera must move')
  await page.clock.runFor(1000)
  const atSpeed = await view()
  await page.clock.runFor(1000)
  const afterSecond = await view()
  assert(Math.abs(Math.abs(afterSecond.angle - atSpeed.angle) - Math.PI / 45) < 0.003, 'the actual camera must turn four degrees per second at maximum speed')
  await page.mouse.move(80, 50)
  assert.equal((await view()).rotating, true, 'hovering must not stop rotation')
  assert.equal((await view()).speed, afterSecond.speed, 'hovering must not restart ease-in')
  await page.mouse.down()
  assert.equal((await view()).rotating, false, 'pressing must stop rotation immediately')
  await page.mouse.move(100, 60, { steps: 4 })
  assert.equal((await view()).rotating, false, 'dragging must keep automatic rotation stopped')
  await page.clock.fastForward(12000)
  assert.equal((await view()).rotating, false, 'holding a pointer must prevent idle rotation')
  await page.mouse.up()
  await page.clock.fastForward(6900)
  assert.equal((await view()).rotating, false, 'releasing the pointer must restart the full wait')
  await page.clock.fastForward(300)
  assert.equal((await view()).rotating, true, 'rotation must resume after the renewed wait')
  await page.mouse.wheel(0, 80)
  await page.clock.runFor(100)
  assert.equal((await view()).rotating, false, 'scrolling must stop rotation')
  await page.clock.fastForward(7200)
  assert.equal((await view()).rotating, true, 'rotation must resume after scrolling')
  await page.keyboard.press('Escape')
  assert.equal((await view()).rotating, false, 'key presses must stop rotation')
  await page.clock.fastForward(7200)
  assert.equal((await view()).rotating, true, 'rotation must resume after key presses')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.runFor(50)
  await page.clock.fastForward(12000)
  assert.equal((await view()).rotating, false, 'reduced motion must disable automatic rotation')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.click('#walk')
  await page.clock.fastForward(12000)
  assert.equal((await view()).rotating, false, 'walking must never trigger orbit rotation')
  await page.click('#walk')
  await page.clock.fastForward(6900)
  assert.equal((await view()).rotating, false, 'returning to overview must restart the full wait')
  await page.clock.fastForward(300)
  assert.equal((await view()).rotating, true, 'overview rotation must resume normally')
  console.log('PASS immediate ease-in, hover ignored, seven-second interaction delay, ninety-second revolution, presses, drags, scrolls, keys, reduced motion and walking')
} finally {
  await browser.close()
}
